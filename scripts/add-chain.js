#!/usr/bin/env node
/**
 * Add EVM chains to the registry from their chain ids - and prove them.
 *
 *   node scripts/add-chain.js 5000 1284 34443        # add, verify, keep what passes
 *   node scripts/add-chain.js 5000 --dry             # report only, write nothing
 *
 * Everything an entry needs is looked up, not typed:
 *
 *   - chainid.network (the ethereum-lists registry): name, short name, the
 *     native coin and its decimals, public RPC endpoints, the explorer.
 *   - the endpoints themselves: each is probed for the chain id it reports;
 *     the block time and the gas price are measured, not assumed.
 *   - CoinGecko: the native coin's price id (asset_platforms), and the USDC /
 *     USDT contracts on the chain (the coin list, native issues preferred
 *     over bridged ones); every contract is then asked for its symbol() and
 *     decimals() on chain, and an entry keeps only what answered correctly.
 *   - Etherscan v2's chain list: whether a free transaction index exists.
 *   - SideShift's coin list: whether payouts can be swapped into or out of it.
 *
 * The entry is written into src/config/chains.js, then scripts/verify-chains.js
 * runs against it; an entry that fails verification is taken out again. The
 * page copy and tables are regenerated by scripts/sync-chain-copy.js, which
 * this runs last. Adding a chain is one command, and nothing about it is
 * copied from a docs page by hand.
 *
 * Read-only against every service; no keys involved.
 */

async function getJson(url, init) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 20000);
  try {
    const response = await fetch(url, { ...init, signal: controller.signal, headers: { accept: 'application/json', ...(init && init.headers) } });
    if (!response.ok) throw new Error(`HTTP ${response.status} from ${url}`);
    return await response.json();
  } finally {
    clearTimeout(timer);
  }
}

async function rpc(url, method, params, timeout = TIMEOUT_MS) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeout);
  try {
    const response = await fetch(url, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }),
      signal: controller.signal,
    });
    const body = await response.json();
    if (body.error) throw new Error(`${method}: ${body.error.message || JSON.stringify(body.error)}`);
    return body.result;
  } finally {
    clearTimeout(timer);
  }
}

function decodeString(hex) {
  if (!hex || hex === '0x') return '';
  const data = hex.slice(2);
  if (data.length < 128) return '';
  const length = parseInt(data.slice(64, 128), 16);
  return Buffer.from(data.slice(128, 128 + length * 2), 'hex').toString('utf8');
}

/** The sources, fetched once for the whole run. */
async function loadSources() {
  process.stdout.write('fetching chainid.network, CoinGecko, Etherscan and SideShift lists…\n');
  const [chainlist, platforms, coinList, etherscan, sideshift] = await Promise.all([
    getJson('https://chainid.network/chains.json'),
    getJson('https://api.coingecko.com/api/v3/asset_platforms'),
    getJson('https://api.coingecko.com/api/v3/coins/list?include_platform=true'),
    getJson('https://api.etherscan.io/v2/chainlist').then((r) => new Set((r.result || []).map((c) => Number(c.chainid)))).catch(() => new Set()),
    getJson('https://sideshift.ai/api/v2/coins').catch(() => []),
  ]);
  return { chainlist, platforms, coinList, etherscan, sideshift };
}

/**
 * The public https endpoints that report the chain's id, up to four: the
 * ones chainid.network lists, then the big public providers guessed by the
 * chain's slug (drpc, publicnode, 1rpc), which serve far more chains than
 * ever get listed. A guess that answers with the right chain id is as good
 * as a listing.
 */
async function probeEndpoints(entry) {
  const listed = (entry.rpc || []).filter((u) => /^https:\/\//.test(u) && !u.includes('${') && !/infura|alchemy\.com\/v2|quiknode|getblock\.io/.test(u));
  const slugs = [...new Set([entry.shortName, entry.name.replace(/\s+(mainnet|network|chain)$/i, ''), entry.name]
    .filter(Boolean).map((s) => String(s).toLowerCase().replace(/\s+mainnet$/, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')))];
  const guessed = slugs.flatMap((slug) => [`https://${slug}.drpc.org`, `https://${slug}-rpc.publicnode.com`, `https://1rpc.io/${slug}`]);
  const candidates = [...new Set([...listed, ...guessed])];
  const kept = [];
  for (const url of candidates) {
    if (kept.length >= 4) break;
    try {
      const id = parseInt(await rpc(url, 'eth_chainId', []), 16);
      if (id !== entry.chainId) continue;
      // and that it answers the calls the app makes
      await rpc(url, 'eth_getBalance', ['0x0000000000000000000000000000000000000000', 'latest']);
      kept.push(url);
    } catch {
      // not answering; the next one
    }
  }
  return kept;
}

async function measure(url) {
  const tipHex = await rpc(url, 'eth_blockNumber', []);
  const tip = parseInt(tipHex, 16);
  const [newest, older, gasPriceHex] = await Promise.all([
    rpc(url, 'eth_getBlockByNumber', [tipHex, false]),
    rpc(url, 'eth_getBlockByNumber', [`0x${Math.max(0, tip - 200).toString(16)}`, false]),
    rpc(url, 'eth_gasPrice', []),
  ]);
  const seconds = newest && older ? (parseInt(newest.timestamp, 16) - parseInt(older.timestamp, 16)) / Math.min(200, tip) : null;
  // The units a plain transfer takes: 21000 on Ethereum, hundreds of
  // thousands on the ZKsync stack, tens of millions on Mantle. Read off
  // real transfers in the last few blocks (their receipts' gasUsed), with
  // an estimate as the fallback and 21000 as the floor.
  let transferGas = 21000;
  const seen = [];
  for (let n = tip; n > tip - 8 && seen.length < 3; n -= 1) {
    let block;
    try { block = await rpc(url, 'eth_getBlockByNumber', [`0x${n.toString(16)}`, true]); } catch { break; }
    for (const tx of (block && block.transactions) || []) {
      if (seen.length >= 3) break;
      if (!tx || tx.input !== '0x' || !tx.to || BigInt(tx.value || '0x0') === 0n) continue;
      try {
        const receipt = await rpc(url, 'eth_getTransactionReceipt', [tx.hash]);
        const used = receipt && parseInt(receipt.gasUsed, 16);
        if (Number.isFinite(used) && used > 0) seen.push(used);
      } catch { /* the next one */ }
    }
  }
  if (seen.length) transferGas = Math.max(21000, ...seen);
  else {
    try {
      const estimated = parseInt(await rpc(url, 'eth_estimateGas', [{ from: '0x000000000000000000000000000000000000dEaD', to: '0x000000000000000000000000000000000000dEaD', value: '0x0' }]), 16);
      if (Number.isFinite(estimated) && estimated >= 21000) transferGas = estimated;
    } catch { /* the floor */ }
  }
  return { tip, blockTimeSec: seconds, gasPriceWei: BigInt(gasPriceHex || '0x0'), transferGas };
}

/** Does at least one endpoint serve a filtered eth_getLogs (capped ranges count)? */
async function servesLogs(urls, contract, tip) {
  for (const url of urls) {
    for (const span of [1000, 200, 50]) {
      try {
        await rpc(url, 'eth_getLogs', [{ address: contract, fromBlock: `0x${Math.max(0, tip - span).toString(16)}`, toBlock: `0x${tip.toString(16)}`, topics: [TRANSFER_TOPIC, '0x0000000000000000000000002222222222222222222222222222222222222222', null] }]);
        return url;
      } catch {
        // narrower, or the next endpoint
      }
    }
  }
  return null;
}

/** The chain's USDC / USDT contracts as CoinGecko lists them, checked on chain. */
async function findTokens(platformId, coinList, urls) {
  const found = {};
  for (const [symbol, idOrder, symbols] of [['USDC', USDC_IDS, USDC_SYMBOLS], ['USDT', USDT_IDS, USDT_SYMBOLS]]) {
    const candidates = coinList
      .filter((c) => c.platforms && c.platforms[platformId] && symbols.includes(String(c.symbol).toLowerCase()) && !BAD_BRIDGES.test(c.id))
      .map((c) => ({ id: c.id, contract: c.platforms[platformId], rank: idOrder.findIndex((re) => re.test(c.id)) }))
      .filter((c) => c.rank >= 0)
      .sort((a, b) => a.rank - b.rank);
    for (const candidate of candidates) {
      let contract;
      try { contract = ethers.getAddress(String(candidate.contract).toLowerCase()); } catch { continue; }
      const proof = await proveToken(urls, contract);
      if (!proof) continue;
      if (!symbols.includes(proof.symbol.toLowerCase())) continue;
      found[symbol] = { contract, decimals: proof.decimals, onChainSymbol: proof.symbol === symbol ? null : proof.symbol, source: candidate.id };
      break;
    }
  }
  return found;
}

async function proveToken(urls, contract) {
  for (const url of urls) {
    try {
      const [s, d] = await Promise.all([
        rpc(url, 'eth_call', [{ to: contract, data: SELECTOR.symbol }, 'latest']),
        rpc(url, 'eth_call', [{ to: contract, data: SELECTOR.decimals }, 'latest']),
      ]);
      const symbol = decodeString(s);
      const decimals = parseInt(d, 16);
      if (!symbol || !Number.isInteger(decimals)) return null;
      return { symbol, decimals };
    } catch {
      // the next endpoint
    }
  }
  return null;
}

/** SideShift's coin + network for the chain's native coin, if it serves it. */
/**
 * Which on-chain swap aggregators serve the chain, proved by asking each
 * for a USDC-to-coin quote. KyberSwap names chains by slug, so a few are
 * guessed from the name; ParaSwap takes the chain id. A chain with no
 * dollar token cannot be probed and gets none.
 */
async function dexFor(entry, tokens) {
  const token = tokens.USDC || tokens.USDT;
  if (!token) return null;
  const NATIVE = '0xeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee';
  const amount = (10n ** BigInt(token.decimals) * 100n).toString();
  const dex = {};
  const clean = (x) => String(x || '').toLowerCase().replace(/\s+(mainnet|network|chain|one|evm)$/i, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  const slugs = [...new Set([clean(entry.shortName), clean(entry.name), clean(entry.name).replace(/-/g, ''), String(entry.nativeCurrency.symbol).toLowerCase()])].filter(Boolean);
  for (const slug of slugs) {
    try {
      const r = await getJson(`https://aggregator-api.kyberswap.com/${slug}/api/v1/routes?tokenIn=${token.contract}&tokenOut=${NATIVE}&amountIn=${amount}`, { headers: { 'x-client-id': 'etheroute' } });
      if (r && r.code === 0 && r.data && r.data.routeSummary) { dex.kyber = slug; break; }
    } catch { /* not this slug */ }
  }
  try {
    const r = await getJson(`https://api.paraswap.io/prices?srcToken=${token.contract}&destToken=${NATIVE}&amount=${amount}&srcDecimals=${token.decimals}&destDecimals=18&side=SELL&network=${entry.chainId}&version=6.2`);
    if (r && r.priceRoute) dex.paraswap = true;
  } catch { /* not served */ }
  return Object.keys(dex).length ? dex : null;
}

// THORChain names its EVM chains itself; a new chain is on it only when
// the network lists it, which is read live.
const THOR_BY_CHAIN_ID = { 1: 'ETH', 56: 'BSC', 43114: 'AVAX', 8453: 'BASE' };
async function thorchainFor(entry) {
  const thorChain = THOR_BY_CHAIN_ID[entry.chainId];
  if (!thorChain) return null;
  try {
    const url = `${process.env.THORNODE_URL || 'https://gateway.liquify.com/chain/thorchain_api/thorchain'}/inbound_addresses`;
    const list = await getJson(url);
    return Array.isArray(list) && list.some((e) => String(e.chain).toUpperCase() === thorChain) ? thorChain : null;
  } catch { return null; }
}

function sideshiftFor(entry, coins) {
  const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const names = new Set([norm(entry.name), norm(entry.shortName), norm(entry.name.replace(/mainnet|network|chain|one|evm/gi, ''))]);
  const symbol = String(entry.nativeCurrency.symbol).toUpperCase();
  for (const coin of coins) {
    if (String(coin.coin).toUpperCase() !== symbol) continue;
    // Exact only. "arbitrumnova" contains "arbitrum", and SideShift's
    // "arbitrum" is Arbitrum One - a loose match would route a payout to
    // the wrong network.
    for (const network of coin.networks || []) {
      if (names.has(norm(network))) return { coin: String(coin.coin).toLowerCase(), network };
    }
  }
  return null;
}

/**
 * A registry code for the chain: the short name where it is short, else the
 * first word of the name (METIS, not METISAND), upper-cased and unique.
 */
function codeFor(entry) {
  const clean = (x) => String(x || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
  const short = clean(entry.shortName);
  const words = String(entry.name || '').replace(/\s+Mainnet$/i, '').split(/[\s-]+/).map(clean).filter(Boolean);
  const symbol = clean(entry.nativeCurrency && entry.nativeCurrency.symbol);
  const symbolTaken = chains.list().some((c) => c.symbol === symbol) || chains.has(symbol);
  // "Arbitrum Nova" is NOVA, not ARBITRUM: the last word when the first
  // already names a chain we have.
  const firstNamesAChain = words.length > 1 && chains.list().some((c) => clean(c.name).startsWith(words[0]));
  let base = short && short.length <= 6 ? short
    : (!symbolTaken && symbol.length >= 3 && symbol.length <= 6) ? symbol
      : (firstNamesAChain ? words[words.length - 1] : words[0] || short).slice(0, 8);
  if (!base) base = `CHAIN${entry.chainId}`;
  if (/^\d/.test(base)) base = `C${base}`;
  let code = base;
  let n = 2;
  while (chains.has(code)) code = `${base}${n++}`;
  return code;
}

function fmtEntry(e) {
  const q = (s) => `'${String(s).replace(/'/g, "\\'")}'`;
  const lines = [];
  lines.push(`  ${e.code}: {`);
  lines.push(`    code: ${q(e.code)},`);
  lines.push(`    name: ${q(e.name)},`);
  lines.push(`    symbol: ${q(e.symbol)},`);
  lines.push("    family: 'evm',");
  lines.push(`    chainId: ${e.chainId},`);
  lines.push('    decimals: 18,');
  lines.push(`    coingeckoId: ${q(e.coingeckoId)},`);
  lines.push(`    rpcEnv: ${q(`${e.code}_RPC_URLS`)},`);
  lines.push(`    rpc: [${e.rpc.map(q).join(', ')}],`);
  if (e.etherscan) lines.push(`    history: [{ kind: 'etherscan', chainId: ${e.chainId} }],`);
  else { lines.push('    // No index on the free tier; checkout reads the blocks over RPC.'); lines.push('    history: [],'); }
  lines.push(`    explorer: { tx: ${q(`${e.explorer}/tx/`)}, address: ${q(`${e.explorer}/address/`)} },`);
  lines.push('    confirmations: 3,');
  lines.push(`    blockTimeSec: ${e.blockTimeSec},`);
  if (e.sideshift) lines.push(`    sideshift: { coin: ${q(e.sideshift.coin)}, network: ${q(e.sideshift.network)} },`);
  else { lines.push('    // SideShift does not serve this network: payouts here are direct only.'); lines.push('    sideshift: null,'); }
  if (e.thorchain) lines.push(`    thorchain: ${q(e.thorchain)},`);
  lines.push(`    directGasUsd: ${e.directGasUsd},`);
  lines.push(`    fallbackGasNative: ${e.fallbackGasNative},`);
  lines.push('    minReserveNative: 0,');
  lines.push('    walletPay: true,');
  if (e.transferGasLimit) {
    lines.push('    // A plain transfer is metered well above 21000 units here; sends');
    lines.push('    // estimate live, this is the floor.');
    lines.push(`    transferGasLimit: ${e.transferGasLimit},`);
  }
  lines.push(`    // Added by scripts/add-chain.js from chainid.network and CoinGecko, verified on chain.`);
  if (e.dex) {
    lines.push(`    dex: { ${Object.entries(e.dex).map(([k, v]) => `${k}: ${typeof v === 'string' ? q(v) : v}`).join(', ')} },`);
  }
  const tokens = Object.entries(e.tokens);
  if (tokens.length) {
    lines.push('    tokens: {');
    for (const [symbol, t] of tokens) {
      lines.push(`      ${symbol}: { contract: ${q(t.contract)}, decimals: ${t.decimals}${t.onChainSymbol ? `, onChainSymbol: ${q(t.onChainSymbol)}` : ''} },`);
    }
    lines.push('    },');
  }
  lines.push('  },');
  return lines.join('\n');
}

/** The file's line ending, by majority: one stray CRLF must not decide it. */
function newlineOf(source) {
  const crlf = (source.match(/\r\n/g) || []).length;
  const lf = (source.match(/\n/g) || []).length - crlf;
  return crlf > lf ? '\r\n' : '\n';
}

function writeEntry(text) {
  let source = fs.readFileSync(REGISTRY, 'utf-8');
  const nl = newlineOf(source);
  const marker = `};${nl}${nl}const CODES = Object.keys(CHAINS);`;
  if (!source.includes(marker)) throw new Error('registry: could not find the end of CHAINS');
  source = source.replace(marker, `${nl}${text.replace(/\n/g, nl)}${nl}};${nl}${nl}const CODES = Object.keys(CHAINS);`);
  fs.writeFileSync(REGISTRY, source);
}

function removeEntry(code) {
  let source = fs.readFileSync(REGISTRY, 'utf-8');
  const nl = newlineOf(source);
  const start = source.indexOf(`${nl}${nl}  ${code}: {`);
  if (start === -1) return;
  const end = source.indexOf(`${nl}  },`, start) + `${nl}  },`.length;
  source = source.slice(0, start) + source.slice(end);
  fs.writeFileSync(REGISTRY, source);
}

async function buildEntry(chainId, sources, log) {
  const entry = sources.chainlist.find((c) => c.chainId === chainId);
  if (!entry) return log.skip(`chain id ${chainId} is not on chainid.network`);
  if (chains.list().some((c) => c.chainId === chainId)) return log.skip(`${entry.name}: already in the registry`);
  if (!entry.nativeCurrency || entry.nativeCurrency.decimals !== 18) return log.skip(`${entry.name}: the native coin is not 18-decimal, which the EVM service assumes`);
  if (/testnet|devnet|sepolia|goerli|holesky/i.test(entry.name) || entry.status === 'deprecated') return log.skip(`${entry.name}: a testnet or deprecated`);

  const rpcs = await probeEndpoints(entry);
  if (rpcs.length < 2) return log.skip(`${entry.name}: only ${rpcs.length} public endpoint(s) answer; the registry needs two to fail over between`);

  const platform = sources.platforms.find((p) => p.chain_identifier === chainId);
  if (!platform) return log.skip(`${entry.name}: CoinGecko does not list the chain as a platform, so its tokens cannot be found`);
  // The coin that pays gas: by its ticker where that is a coin we know, else
  // the platform's own native coin when its ticker agrees with the chain's.
  const symbol = String(entry.nativeCurrency.symbol).toUpperCase();
  let coingeckoId = NATIVE_BY_SYMBOL[symbol] || null;
  if (!coingeckoId && platform.native_coin_id) {
    const coin = sources.coinList.find((c) => c.id === platform.native_coin_id);
    if (coin && String(coin.symbol).toUpperCase() === symbol) coingeckoId = coin.id;
  }
  if (!coingeckoId) return log.skip(`${entry.name}: no CoinGecko coin found for its native ${symbol}, so it cannot be priced`);

  const measured = await measure(rpcs[0]);
  if (!measured.blockTimeSec || measured.blockTimeSec <= 0) return log.skip(`${entry.name}: could not measure a block time`);
  const blockTimeSec = measured.blockTimeSec < 1 ? Math.round(measured.blockTimeSec * 10) / 10 || 0.1 : Math.round(measured.blockTimeSec);

  const tokens = await findTokens(platform.id, sources.coinList, rpcs);
  const tokenSymbols = Object.keys(tokens);
  let logsUrl = null;
  if (tokenSymbols.length) {
    logsUrl = await servesLogs(rpcs, tokens[tokenSymbols[0]].contract, measured.tip);
    if (!logsUrl) return log.skip(`${entry.name}: no endpoint serves eth_getLogs, so a token payment could not be settled`);
  }

  // the coin's price, for the gas figure (CoinGecko's free tier rate-limits;
  // a 429 is waited out, not taken as "no price")
  const price = await priceOf(coingeckoId);
  if (!price) return log.skip(`${entry.name}: CoinGecko has no price for ${coingeckoId}`);
  const gasNative = Number(ethers.formatEther(measured.gasPriceWei * BigInt(measured.transferGas)));
  const directGasUsd = Math.max(0.001, Math.round(gasNative * price * 1000) / 1000);
  const fallbackGasNative = Math.max(0.00001, Math.round(gasNative * 3 * 1e8) / 1e8);
  // a chain that meters a transfer well above 21000 states a floor for sends
  const transferGasLimit = measured.transferGas > 35000 ? Math.ceil((measured.transferGas * 1.5) / 1000) * 1000 : null;

  const explorer = ((entry.explorers || []).find((x) => /^https:\/\//.test(x.url)) || {}).url;
  if (!explorer) return log.skip(`${entry.name}: no explorer listed`);

  return {
    code: codeFor(entry),
    // "katana" -> "Katana"; chainid.network is not consistent about case
    name: entry.name.replace(/\s+Mainnet$/i, '').replace(/^[a-z]/, (c) => c.toUpperCase()),
    symbol: String(entry.nativeCurrency.symbol).toUpperCase(),
    chainId,
    coingeckoId,
    rpc: rpcs,
    etherscan: sources.etherscan.has(chainId),
    explorer: explorer.replace(/\/$/, ''),
    blockTimeSec,
    sideshift: sideshiftFor(entry, sources.sideshift),
    thorchain: await thorchainFor(entry),
    dex: await dexFor(entry, tokens),
    directGasUsd,
    fallbackGasNative,
    transferGasLimit,
    transferGas: measured.transferGas,
    tokens,
    logsUrl,
    price,
  };
}

const priceCache = new Map();
async function priceOf(id) {
  if (priceCache.has(id)) return priceCache.get(id);
  for (let attempt = 0; attempt < 4; attempt += 1) {
    try {
      const p = await getJson(`https://api.coingecko.com/api/v3/simple/price?ids=${id}&vs_currencies=usd`);
      const price = Number(p[id] && p[id].usd) || 0;
      priceCache.set(id, price);
      return price;
    } catch (error) {
      if (!/HTTP 429/.test(error.message)) { priceCache.set(id, 0); return 0; }
      await new Promise((r) => setTimeout(r, 15000 * (attempt + 1)));
    }
  }
  return 0;
}

async function main() {
  if (ids.length === 0) {
    process.stdout.write('usage: node scripts/add-chain.js <chainId> [<chainId>…] [--dry]\n');
    process.exit(2);
  }
  const sources = await loadSources();
  const added = [];
  const skipped = [];
  for (const chainId of ids) {
    const log = { skip: (why) => { skipped.push(why); process.stdout.write(`  skip  ${why}\n`); return null; } };
    let built;
    try {
      built = await buildEntry(chainId, sources, log);
    } catch (error) {
      log.skip(`chain id ${chainId}: ${error.message}`);
      continue;
    }
    if (!built) continue;
    const tokens = Object.entries(built.tokens).map(([s, t]) => `${s}${t.onChainSymbol ? ` (${t.onChainSymbol})` : ''} ${t.decimals}dp via ${t.source}`).join(', ') || 'none';
    process.stdout.write(`  ${built.code.padEnd(8)} ${built.name} · ${built.symbol} @ $${built.price} · ${built.rpc.length} rpcs · ${built.blockTimeSec}s blocks · ${built.transferGas} gas/transfer ~$${built.directGasUsd} · index ${built.etherscan ? 'etherscan' : 'none'} · swaps ${built.sideshift ? built.sideshift.network : 'no'} · on-chain ${built.dex ? Object.keys(built.dex).join('+') : 'no'} · thorchain ${built.thorchain || 'no'} · tokens: ${tokens}\n`);
    if (DRY) continue;
    writeEntry(fmtEntry(built));
    // prove it the way every other entry is proved; take it out if it fails
    try {
      execFileSync(process.execPath, [path.join(__dirname, 'verify-chains.js'), built.code, '--skip-prices'], { stdio: 'pipe', timeout: 120000 });
      added.push(built.code);
      process.stdout.write(`  ok    ${built.code} verified and written\n`);
    } catch (error) {
      removeEntry(built.code);
      const out = String(error.stdout || error.message).split('\n').filter((l) => /FAIL/.test(l)).join('; ');
      log.skip(`${built.name}: failed verification, removed - ${out || error.message}`);
    }
  }
  if (added.length && !DRY) {
    process.stdout.write(`\nregenerating the page copy for ${chains.CODES.length + added.length} chains…\n`);
    execFileSync(process.execPath, [path.join(__dirname, 'sync-chain-copy.js')], { stdio: 'inherit' });
  }
  process.stdout.write(`\n${added.length} added${skipped.length ? `, ${skipped.length} skipped` : ''}${DRY ? ' (dry run: nothing written)' : ''}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error.stack}\n`);
  process.exit(1);
});
